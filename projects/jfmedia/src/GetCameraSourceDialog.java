  public Camera getCamera() {
    int width;
    int height;
    try {
      int idx = cameraList.getSelectedIndex();
      if (idx == -1) return null;
      JFLog.log("cameraIdx=" + idx);
      camera = new Camera();
      if (!camera.init()) return null;
      camera.listDevices();
      String[] modes = camera.listModes(idx);
      if (modes != null) {
        for(String mode : modes) {
          JFLog.log("mode=" + mode);
        }
        String mode = modes[0];  //640x480
        String[] w_h = mode.split("x");
        width = Integer.valueOf(w_h[0]);
        height = Integer.valueOf(w_h[1]);
      } else {
        JFLog.log("Error:no camera modes available?");
        width = 640;
        height = 480;
      }
      JFLog.log("camera:" + idx + ":" + width + "x" + height);
      if (!camera.start(idx, width, height)) {
        JFLog.log("Camera.start() failed!");
        return null;
      }
      return camera;
    } catch (Exception e) {
      JFLog.log(e);
      return null;
    }
  }

  public AudioInput getAudio() {
    try {
      int idx = audioList.getSelectedIndex();
      if (idx == -1) return null;
      audio.start(2, 48000, 16, 1024, audioDevs[idx]);
      return audio;
    } catch (Exception e) {
      JFLog.log(e);
      return null;
    }
  }
