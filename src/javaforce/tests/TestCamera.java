  private void startActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_startActionPerformed
    setState(false);
    camera = new Camera();
    if (!camera.init()) {
      JFAWT.showError("Error", "Camera init failed");
      return;
    }
    String[] devices = camera.listDevices();
    if (devices == null || devices.length == 0) {
      camera.uninit();
      JFAWT.showError("Error", "No camera found");
    }
    int camIdx = cameraList.getSelectedIndex();
    if (camIdx < 0 || camIdx >= devices.length) {
      camIdx = 0;
    }
    String mode = (String)modeList.getSelectedItem();
    if (mode == null) {
      mode = "640x480";
    }
    String[] w_h = mode.split("x");
    width = Integer.valueOf(w_h[0]);
    height = Integer.valueOf(w_h[1]);
    JFLog.log("camera=" + devices[camIdx]);
    JFLog.log("mode=" + mode);
    for(int a=0;a<3;a++) {JFLog.log(" ------------------------------- ");}
    camera.start(camIdx, width, height);
    width = camera.getWidth();
    height = camera.getHeight();
    JFLog.log("real mode=" + width + "x" + height);
    timer = new Timer();
    timer.scheduleAtFixedRate(new TimerTask() {
      public void run() {
        java.awt.EventQueue.invokeLater(new Runnable() {public void run() {
          boolean m = mirror.isSelected();
          boolean f = flip.isSelected();
          int[] px = m ? (f ? camera.getFrameMirrorAndFlip() : camera.getFrameMirror() ) : (f ? camera.getFrameFlip() : camera.getFrame());
          if (px == null) return;  //not ready
          if (img == null || img.getWidth() != width || img.getHeight() != height) {
            img = new JFImage(width, height);
          }
          System.arraycopy(px, 0, img.getBuffer(), 0, width * height);
          int dst_width = preview.getWidth();
          int dst_height = preview.getHeight();
          if (width == dst_width && height == dst_height) {
            preview.setIcon(img);
          } else {
            //rescale image
            if (dst_img == null || dst_img.getWidth() != dst_width || dst_img.getHeight() != dst_height) {
              dst_img = new JFImage(dst_width, dst_height);
            }
            dst_img.putJFImageScale(img, 0, 0, dst_width, dst_height);
            preview.setIcon(dst_img);
          }
          preview.repaint();
          JFLog.log("addFrame:" + frameCount++);
          JFLog.log("============================");
        }});
      }
    }, 100, 100);
  }//GEN-LAST:event_startActionPerformed

